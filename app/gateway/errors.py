"""Stable, client-safe errors emitted by the MCP gateway."""

from enum import Enum

from pydantic import BaseModel


class GatewayErrorCode(str, Enum):
    INVALID_AGENT = "INVALID_AGENT"
    INVALID_TOOL_NAME = "INVALID_TOOL_NAME"
    UNKNOWN_SERVER = "UNKNOWN_SERVER"
    UNKNOWN_TOOL = "UNKNOWN_TOOL"
    PERMISSION_DENIED = "PERMISSION_DENIED"
    POLICY_DENIED = "POLICY_DENIED"
    APPROVAL_REQUIRED = "APPROVAL_REQUIRED"
    DOWNSTREAM_UNAVAILABLE = "DOWNSTREAM_UNAVAILABLE"
    DOWNSTREAM_TIMEOUT = "DOWNSTREAM_TIMEOUT"
    SECURITY_EVALUATION_FAILED = "SECURITY_EVALUATION_FAILED"
    APPROVAL_NOT_FOUND = "APPROVAL_NOT_FOUND"
    APPROVAL_DENIED = "APPROVAL_DENIED"
    APPROVAL_EXPIRED = "APPROVAL_EXPIRED"
    APPROVAL_TIMED_OUT = "APPROVAL_TIMED_OUT"
    APPROVAL_ALREADY_CONSUMED = "APPROVAL_ALREADY_CONSUMED"
    APPROVAL_ARGUMENT_MISMATCH = "APPROVAL_ARGUMENT_MISMATCH"
    APPROVAL_BINDING_CHANGED = "APPROVAL_BINDING_CHANGED"
    APPROVAL_TOOL_MISMATCH = "APPROVAL_TOOL_MISMATCH"
    APPROVAL_DESTINATION_MISMATCH = "APPROVAL_DESTINATION_MISMATCH"
    APPROVAL_ENVIRONMENT_MISMATCH = "APPROVAL_ENVIRONMENT_MISMATCH"
    APPROVAL_SECURITY_CONTEXT_MISMATCH = "APPROVAL_SECURITY_CONTEXT_MISMATCH"
    FRESH_DECISION_REQUIRED = "FRESH_DECISION_REQUIRED"
    SESSION_NOT_FOUND = "SESSION_NOT_FOUND"
    SESSION_OWNERSHIP_MISMATCH = "SESSION_OWNERSHIP_MISMATCH"
    AUDIT_EVENT_NOT_FOUND = "AUDIT_EVENT_NOT_FOUND"
    POLICY_NOT_FOUND = "POLICY_NOT_FOUND"
    POLICY_VERSION_NOT_FOUND = "POLICY_VERSION_NOT_FOUND"
    POLICY_STALE = "POLICY_STALE"
    POLICY_DISABLED = "POLICY_DISABLED"
    POLICY_INVALID = "POLICY_INVALID"
    POLICY_VERSION_MISMATCH = "POLICY_VERSION_MISMATCH"
    CONTEXT_CONFLICT = "CONTEXT_CONFLICT"
    UNKNOWN_WORKFLOW = "UNKNOWN_WORKFLOW"
    INVALID_WORKFLOW_CONTEXT = "INVALID_WORKFLOW_CONTEXT"
    UNTRUSTED_CONTEXT_OVERRIDE = "UNTRUSTED_CONTEXT_OVERRIDE"
    POLICY_CONFLICT = "POLICY_CONFLICT"
    SIMULATION_ONLY = "SIMULATION_ONLY"
    POLICY_REGRESSION_FAILURE = "POLICY_REGRESSION_FAILURE"


class GatewayError(BaseModel):
    code: GatewayErrorCode
    message: str
    request_id: str
    tool_name: str
    decision: str | None = None
    matched_policy: str | None = None
    risk_score: int | None = None
    risk_level: str | None = None
    approval_id: str | None = None
    fresh_decision_required: bool = False
    changed_fields: list[str] = []
